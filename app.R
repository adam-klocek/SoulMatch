library(shiny)
library(bslib)
for (file in c("utils", "migrations", "database", "questionnaires", "interests_data", "interest_features", "matching", "photos", "height", "interests_modules", "demo", "world", "ui", "server")) source(file.path("R", paste0(file, ".R")), local = TRUE)
options(soulmatch.www_dir = normalizePath("www"))
options(shiny.maxRequestSize = 5 * 1024^2, shiny.sanitize.errors = TRUE)
data_dir <- Sys.getenv("SOULMATCH_DATA_DIR", Sys.getenv("KINDRED_DATA_DIR", "data"))
dir.create(data_dir, recursive = TRUE, showWarnings = FALSE, mode = "0700")
db_path <- resolve_db_path(data_dir)
photo_dir <- file.path(data_dir, "photos")
questionnaires <- load_registry()
algorithms <- algorithm_registry(questionnaires)
demo_mode <- tolower(Sys.getenv("SOULMATCH_DEMO_MODE", "true")) == "true"
startup <- open_db(db_path)
seed_interest_catalog(startup, load_interest_catalog())
if (demo_mode) seed_demo(startup, questionnaires)
DBI::dbDisconnect(startup)
shinyApp(app_ui(demo_mode, algorithms, questionnaires), function(input, output, session) {
  app_server(input, output, session, db_path, photo_dir, questionnaires, algorithms, demo_mode)
})
