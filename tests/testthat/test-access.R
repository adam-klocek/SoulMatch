testthat::test_that("authentication, profile validation, and parameterized SQL work", {
  f <- fixture()
  testthat::expect_identical(authenticate(f$con, "alex", "SoulMatchDemo!2026"), f$ids$alex)
  testthat::expect_null(authenticate(f$con, "alex", "wrong"))
  testthat::expect_null(authenticate(f$con, "' OR 1=1 --", "wrong"))
  testthat::expect_error(register_user(f$con, "ab", "long-enough-password"), "3–30")
  testthat::expect_error(register_user(f$con, "new_user", "short"), "12–200")
  p <- get_profile(f$con, f$ids$alex); p$age <- 17
  testthat::expect_error(save_profile(f$con, f$ids$alex, p), "adults")
  p$age <- 29; p$preferences$age <- c(40, 20)
  testthat::expect_error(save_profile(f$con, f$ids$alex, p), "range")
  p$preferences <- DEFAULT_PREFS; p$consent <- FALSE; p$bio <- "<script>alert('x')</script>"
  save_profile(f$con, f$ids$alex, p)
  testthat::expect_match(as.character(shiny::tags$p(get_profile(f$con, f$ids$alex)$bio)), "&lt;script&gt;", fixed = TRUE)
})
testthat::test_that("chat requires mutual likes; blocks revoke chat and photo access", {
  f <- fixture(); a <- f$ids$alex; b <- f$ids$maya; c <- f$ids$leo
  testthat::expect_false(is_mutual(f$con, a, b))
  testthat::expect_error(send_message(f$con, a, b, "hello"), "mutual")
  testthat::expect_error(save_decision(f$con, a, b, "like", "forged", f$registry), "Refresh")
  save_decision(f$con, a, b, "like", make_impression(f, a, b), f$registry)
  testthat::expect_true(is_mutual(f$con, a, b))
  send_message(f$con, a, b, "hello Maya")
  testthat::expect_identical(read_messages(f$con, b, a)$body, "hello Maya")
  testthat::expect_error(read_messages(f$con, c, a), "unavailable")
  DBI::dbExecute(f$con, "INSERT INTO blocks VALUES(?,?,?)", params = list(b, a, now_utc()))
  testthat::expect_false(is_mutual(f$con, a, b))
  testthat::expect_error(send_message(f$con, a, b, "still there?"), "mutual")
  testthat::expect_error(read_messages(f$con, a, b), "unavailable")
  testthat::expect_error(photo_path(f$con, a, b, tempfile(), f$registry), "unavailable")
  testthat::expect_false(eligible_pair(f$con, get_profile(f$con, a), get_profile(f$con, b)))
})
testthat::test_that("uploads are decoded and account deletion cascades", {
  f <- fixture(); folder <- tempfile(); dir.create(folder); withr::defer(unlink(folder, recursive = TRUE))
  path <- tempfile(fileext = ".png"); png::writePNG(array(.5, dim = c(4, 4, 3)), path)
  upload <- data.frame(name = "../../fake.jpg", size = file.info(path)$size, type = "text/plain", datapath = path)
  photo_id <- save_photo(f$con, f$ids$alex, upload, folder)
  testthat::expect_true(file.exists(photo_path(f$con, f$ids$alex, f$ids$alex, folder, f$registry)))
  testthat::expect_true(file.exists(photo_path(f$con, f$ids$maya, f$ids$alex, folder, f$registry)))
  fake <- tempfile(); writeLines("<svg onload='alert(1)'/>", fake); upload$datapath <- fake
  testthat::expect_error(save_photo(f$con, f$ids$alex, upload, folder), "real PNG")
  delete_account(f$con, f$ids$alex, folder)
  testthat::expect_null(get_profile(f$con, f$ids$alex))
  testthat::expect_equal(nrow(DBI::dbGetQuery(f$con, "SELECT 1 FROM responses WHERE user_id=?", params = list(f$ids$alex))), 0)
  testthat::expect_equal(nrow(DBI::dbGetQuery(f$con, "SELECT 1 FROM decisions WHERE actor_id=? OR target_id=?", params = list(f$ids$alex, f$ids$alex))), 0)
  testthat::expect_length(list.files(folder), 0)
})
