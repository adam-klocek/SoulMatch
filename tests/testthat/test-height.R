testthat::test_that("Brno height scoring matches the original sum and regression", {
  f <- fixture(); answers <- as.list(rep(2, 11)); names(answers) <- paste0("p", 1:11)
  result <- score_height(answers, "men")
  testthat::expect_equal(result$raw_score, 16)
  testthat::expect_equal(result$estimate_cm, 161.22621 + 1.0424 * 16)
  testthat::expect_lt(result$lower_cm, result$estimate_cm)
  testthat::expect_gt(result$upper_cm, result$estimate_cm)
  testthat::expect_true(is.na(score_height(answers, "none")$estimate_cm))
  testthat::expect_error(score_height(answers[-1]), "11 height")
  testthat::expect_error(score_height(answers, "nonbinary"), "reference")
  save_height(f$con, f$ids$alex, answers, "men", FALSE)
  testthat::expect_true(is.na(get_profile(f$con, f$ids$alex)$height))
  save_height(f$con, f$ids$alex, answers, "women", TRUE)
  testthat::expect_equal(get_profile(f$con, f$ids$alex)$height, score_height(answers, "women")$estimate_cm)
  p <- get_profile(f$con, f$ids$alex); p$height <- 245
  save_profile(f$con, f$ids$alex, p)
  testthat::expect_equal(get_profile(f$con, f$ids$alex)$height, score_height(answers, "women")$estimate_cm)
  save_height(f$con, f$ids$alex, answers, "none", TRUE)
  testthat::expect_true(is.na(get_profile(f$con, f$ids$alex)$height))
  testthat::expect_equal(nrow(DBI::dbGetQuery(f$con, "SELECT 1 FROM height_responses WHERE user_id=?", params = list(f$ids$alex))), 3)
})
testthat::test_that("the height Shiny module saves drafts and does not infer a reference from identity", {
  f <- fixture(); uid <- shiny::reactiveVal(f$ids$alex)
  shiny::testServer(heightModuleServer, args = list(con = f$con, user = uid), {
    testthat::expect_match(output$form$html, "No centimetre estimate", fixed = TRUE)
    testthat::expect_false(grepl('type="number"', output$form$html, fixed = TRUE))
    inputs <- as.list(rep("1", 11)); names(inputs) <- paste0("p", 1:11); do.call(session$setInputs, inputs)
    session$setInputs(reference = "none", allow = TRUE, save_draft = 1)
    testthat::expect_equal(nrow(DBI::dbGetQuery(f$con, "SELECT 1 FROM response_drafts WHERE user_id=? AND instrument_id='brno_height11'", params = list(f$ids$alex))), 1)
    session$setInputs(complete = 1)
    testthat::expect_true(is.na(get_profile(f$con, f$ids$alex)$height))
    testthat::expect_match(output$result$html, "No centimetre estimate requested", fixed = TRUE)
  })
})
