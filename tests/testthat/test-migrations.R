testthat::test_that("a legacy database loses retired measurements and retains accounts and Love chat", {
  path <- tempfile(fileext = ".sqlite"); con <- DBI::dbConnect(RSQLite::SQLite(), path)
  DBI::dbExecute(con, "CREATE TABLE schema_version(version INTEGER PRIMARY KEY)")
  DBI::dbExecute(con, "INSERT INTO schema_version VALUES(1)")
  DBI::dbExecute(con, "CREATE TABLE users(id TEXT PRIMARY KEY,username TEXT UNIQUE,password_hash TEXT,created_at TEXT,is_demo INTEGER DEFAULT 0)")
  DBI::dbExecute(con, "CREATE TABLE profiles(user_id TEXT PRIMARY KEY REFERENCES users(id),name TEXT,age INTEGER,gender TEXT,interested TEXT,city TEXT,bio TEXT,height REAL,weight REAL,income TEXT,style TEXT,smoking TEXT,goal TEXT,hobbies TEXT,preferences TEXT,consent INTEGER,updated_at TEXT)")
  DBI::dbExecute(con, "CREATE TABLE decisions(actor_id TEXT REFERENCES users(id),target_id TEXT REFERENCES users(id),decision TEXT,updated_at TEXT,PRIMARY KEY(actor_id,target_id))")
  DBI::dbExecute(con, "CREATE TABLE messages(id INTEGER PRIMARY KEY,sender_id TEXT REFERENCES users(id),receiver_id TEXT REFERENCES users(id),body TEXT,created_at TEXT)")
  hash <- sodium::password_store("a-legacy-strong-password")
  for (id in c("a", "b")) {
    DBI::dbExecute(con, "INSERT INTO users VALUES(?,?,?,?,0)", params = list(id, paste0("user_", id), hash, now_utc()))
    DBI::dbExecute(con, "INSERT INTO profiles VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)", params = list(id, id, 29L, "Nonbinary", '["Nonbinary"]', "Prague", "legacy", 175, 80, INCOMES[1], "Casual", "No", GOALS[1], '[]', '{"age":[22,45],"weight":[60,90],"hard_weight":true}', 0L, now_utc()))
  }
  DBI::dbExecute(con, "INSERT INTO decisions VALUES('a','b','like','2026-01-01')")
  DBI::dbExecute(con, "INSERT INTO decisions VALUES('b','a','like','2026-01-01')")
  DBI::dbExecute(con, "INSERT INTO messages VALUES(1,'a','b','Kept conversation','2026-01-01T12:00:00Z')")
  DBI::dbDisconnect(con); con <- open_db(path); withr::defer(DBI::dbDisconnect(con))
  testthat::expect_false("weight" %in% DBI::dbListFields(con, "profiles"))
  p <- get_profile(con, "a")
  testthat::expect_false(any(grepl("weight", names(p$preferences))))
  testthat::expect_true(is.na(p$height))
  testthat::expect_identical(p$connection_modes, "love")
  testthat::expect_identical(authenticate(con, "user_a", "a-legacy-strong-password"), "a")
  testthat::expect_true(is_mutual(con, "a", "b", "love"))
  testthat::expect_false(is_mutual(con, "a", "b", "friends"))
  testthat::expect_identical(read_messages(con, "a", "b", "love")$body, "Kept conversation")
  testthat::expect_equal(max(DBI::dbGetQuery(con, "SELECT version FROM schema_version")$version), 4)
  testthat::expect_false(migrate_soulmatch(con))
  folder <- tempfile(); dir.create(folder); withr::defer(unlink(folder, recursive=TRUE))
  file.create(file.path(folder, "kindred.sqlite"))
  testthat::expect_identical(basename(resolve_db_path(folder)), "kindred.sqlite")
  file.create(file.path(folder, "soulmatch.sqlite"))
  testthat::expect_identical(basename(resolve_db_path(folder)), "soulmatch.sqlite")
})
