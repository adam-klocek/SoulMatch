testthat::test_that("Friends uses mutual opt-in without romantic gender or partner filters", {
  f <- fixture(); a <- get_profile(f$con, f$ids$leo); b <- get_profile(f$con, f$ids$jamie)
  testthat::expect_false(eligible_pair(f$con, a, b, "love"))
  a$preferences$hard_income <- TRUE; a$preferences$income <- INCOMES[2]
  a$preferences$hard_age <- TRUE; a$preferences$age <- c(70, 90)
  testthat::expect_true(eligible_pair(f$con, a, b, "friends"))
  b$connection_modes <- "love"; testthat::expect_false(eligible_pair(f$con, a, b, "friends"))
  a$connection_modes <- "friends"; a$interested <- character(); a$consent <- FALSE
  save_profile(f$con, a$user_id, a)
  testthat::expect_identical(get_profile(f$con, a$user_id)$connection_modes, "friends")
  b <- get_profile(f$con, f$ids$jamie)
  x <- pair_features(f$con, a, b, f$registry, mode = "friends")
  testthat::expect_equal(x[["is_friend_mode"]], 1)
  testthat::expect_equal(x[["own_preferences"]], 1)
})
testthat::test_that("requests, passes, chat and pausing are independent by mode", {
  f <- fixture(); a <- f$ids$alex; b <- f$ids$maya
  imp <- function(mode) log_impression(f$con, a, b, f$algorithms$balanced, f$registry, pair_features(f$con, get_profile(f$con, a), get_profile(f$con, b), f$registry, mode = mode), mode)
  love <- imp("love")
  testthat::expect_error(save_decision(f$con, a, b, "like", love, f$registry, "friends"), "Refresh")
  save_decision(f$con, a, b, "pass", love, f$registry, "love")
  testthat::expect_false(is_mutual(f$con, a, b, "love"))
  friends <- discover(f$con, get_profile(f$con, a), f$registry, f$algorithms$balanced, mode = "friends")
  testthat::expect_true(b %in% vapply(friends, function(x) x$profile$user_id, ""))
  save_decision(f$con, a, b, "like", imp("friends"), f$registry, "friends")
  testthat::expect_true(is_mutual(f$con, a, b, "friends"))
  testthat::expect_error(send_message(f$con, a, b, "Wrong channel", "love"), "mutual")
  send_message(f$con, a, b, "Friends hello", "friends")
  testthat::expect_identical(read_messages(f$con, b, a, "friends")$body, "Friends hello")
  save_decision(f$con, a, b, "like", imp("love"), f$registry, "love")
  send_message(f$con, a, b, "Love hello", "love")
  testthat::expect_identical(read_messages(f$con, b, a, "love")$body, "Love hello")
  testthat::expect_identical(read_messages(f$con, b, a, "friends")$body, "Friends hello")
  p <- get_profile(f$con, a); p$connection_modes <- "friends"; save_profile(f$con, a, p)
  testthat::expect_false(is_mutual(f$con, a, b, "love"))
  testthat::expect_error(read_messages(f$con, a, b, "love"), "unavailable")
  testthat::expect_true(is_mutual(f$con, a, b, "friends"))
  DBI::dbExecute(f$con, "INSERT INTO blocks VALUES(?,?,?)", params = list(a, b, now_utc()))
  testthat::expect_false(is_mutual(f$con, a, b, "friends"))
  testthat::expect_error(send_message(f$con, b, a, "After a block", "friends"), "mutual")
})
