testthat::test_that("context preferences distinguish essentials, soft wishes, friendship and availability", {
  f<-fixture();a<-f$ids$alex;b<-f$ids$maya
  x<-member_context(f$con,a);x$preferences$children<-list(values=list("Want children"),importance="essential")
  save_member_context(f$con,a,x)
  testthat::expect_false(eligible_pair(f$con,get_profile(f$con,a),get_profile(f$con,b),"love"))
  testthat::expect_true(eligible_pair(f$con,get_profile(f$con,a),get_profile(f$con,b),"friends"))
  y<-member_context(f$con,b);y$attributes$children<-"Want children";y$beyond$sunday<-"Coffee and a long walk";save_member_context(f$con,b,y)
  testthat::expect_true(eligible_pair(f$con,get_profile(f$con,a),get_profile(f$con,b),"love"))
  x$preferences$children$importance<-"strong";save_member_context(f$con,a,x)
  y$attributes$children<-"Do not want children";save_member_context(f$con,b,y)
  testthat::expect_true(eligible_pair(f$con,get_profile(f$con,a),get_profile(f$con,b),"love"))
  testthat::expect_equal(context_fit(x,y),0)
  x$availability<-"paused";save_member_context(f$con,a,x)
  testthat::expect_false(eligible_pair(f$con,get_profile(f$con,a),get_profile(f$con,b),"friends"))
  testthat::expect_error(save_member_context(f$con,a,modifyList(x,list(availability="secret"))),"availability")
})
testthat::test_that("daily collections persist, obey eligibility, save separately and record real served events once", {
  f<-fixture();a<-f$ids$alex;registered_algorithms(f$con,f$algorithms)
  card<-daily_connection(f$con,a,f$registry,f$algorithms,f$algorithms$balanced,"friends")
  testthat::expect_true(!is.null(card))
  count<-DBI::dbGetQuery(f$con,"SELECT COUNT(*) AS n FROM daily_connections")$n[[1]]
  testthat::expect_equal(count,6)
  again<-daily_connection(f$con,a,f$registry,f$algorithms,f$algorithms$balanced,"friends")
  testthat::expect_identical(card$profile$user_id,again$profile$user_id)
  testthat::expect_identical(card$impression_id,again$impression_id)
  testthat::expect_equal(DBI::dbGetQuery(f$con,"SELECT COUNT(*) AS n FROM impressions WHERE actor_id=?",params=list(a))$n,1)
  save_for_later(f$con,a,card$profile$user_id,"friends")
  next_card<-daily_connection(f$con,a,f$registry,f$algorithms,f$algorithms$balanced,"friends")
  testthat::expect_false(identical(next_card$profile$user_id,card$profile$user_id))
  testthat::expect_equal(nrow(DBI::dbGetQuery(f$con,"SELECT 1 FROM decisions WHERE actor_id=? AND mode='friends'",params=list(a))),0)
  probs<-DBI::dbGetQuery(f$con,"SELECT selection_probability FROM daily_connections")$selection_probability
  testthat::expect_true(all(probs>0&probs<=1))
  daily_connection(f$con,a,f$registry,f$algorithms,f$algorithms$balanced,"friends",more=TRUE)
  testthat::expect_equal(DBI::dbGetQuery(f$con,"SELECT COUNT(*) AS n FROM daily_connections")$n,7)
  ids<-DBI::dbGetQuery(f$con,"SELECT target_id FROM daily_connections")$target_id
  testthat::expect_equal(length(unique(ids)),7)
  DBI::dbExecute(f$con,"UPDATE users SET status='suspended' WHERE id=?",params=list(next_card$profile$user_id))
  current<-daily_connection(f$con,a,f$registry,f$algorithms,f$algorithms$balanced,"friends")
  testthat::expect_false(identical(current$profile$user_id,next_card$profile$user_id))
})
