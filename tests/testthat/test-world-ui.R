    state <- app_server(input, output, session, f$path, tempfile(), f$registry, f$algorithms, TRUE)
    active_module <- state$active_module; page <- state$page; con <- state$con; user <- state$user
    questionnaires <- f$registry; algorithms <- f$algorithms; candidate <- state$candidate; impression <- state$impression
