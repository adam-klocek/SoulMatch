testthat::test_that("My world separates pending and mutual cards with aggregate-only metrics", {
  f <- fixture(); a <- f$ids$alex; b <- f$ids$maya; d <- f$ids$leo
  testthat::expect_length(connection_summaries(f$con, a, f$registry, f$algorithms), 0)
  save_decision(f$con, a, b, "like", make_impression(f, a, b), f$registry, "love")
  x <- pair_features(f$con, get_profile(f$con, a), get_profile(f$con, d), f$registry, mode = "friends")
  imp <- log_impression(f$con, a, d, f$algorithms$balanced, f$registry, x, "friends")
  save_decision(f$con, a, d, "like", imp, f$registry, "friends")
  cards <- connection_summaries(f$con, a, f$registry, f$algorithms)
  testthat::expect_length(cards, 2)
  mutual <- Filter(function(c) c$id == b, cards)[[1]]; pending <- Filter(function(c) c$id == d, cards)[[1]]
  testthat::expect_identical(mutual$status, "mutual")
  testthat::expect_identical(pending$status, "pending")
  testthat::expect_length(mutual$metrics, 7)
  image <- tempfile(fileext = ".png"); png::writePNG(array(.6, c(8, 8, 3)), image)
  photo_id <- save_photo(f$con, b, data.frame(size = file.info(image)$size, datapath = image), tempfile())
  refreshed <- Filter(function(c) c$id == b, connection_summaries(f$con, a, f$registry, f$algorithms))[[1]]
  testthat::expect_identical(refreshed$photo_key, photo_id)
  testthat::expect_true(all(is.na(pending$metrics[c("Your preference fit", "Their preference fit")])))
  testthat::expect_true(all(mutual$metrics[is.finite(mutual$metrics)] >= 0 & mutual$metrics[is.finite(mutual$metrics)] <= 1))
  testthat::expect_setequal(names(mutual), c("photo_key", "id", "mode", "status", "name", "age", "gender", "city", "portrait", "metrics"))
  testthat::expect_false(any(c("answers", "responses", "income", "preferences", "scores", "lifestyle", "details") %in% names(mutual)))
  DBI::dbExecute(f$con, "INSERT INTO blocks VALUES(?,?,?)", params = list(b, a, now_utc()))
  testthat::expect_false(any(vapply(connection_summaries(f$con, a, f$registry, f$algorithms), function(c) c$id == b, TRUE)))
  p <- get_profile(f$con, d); p$connection_modes <- "love"; save_profile(f$con, d, p)
  testthat::expect_length(connection_summaries(f$con, a, f$registry, f$algorithms), 0)
})
